"""Generate one random API key per service for a topology.

Writes ``secrets/<topology name>.toml`` (git-ignored). Existing keys are kept unless
``--force`` is given, so re-running after adding a service only adds the new key.

    uv run python scripts/gen_keys.py topologies/t1-ports.toml
"""

from __future__ import annotations

import argparse
import secrets
import sys
import tomllib
from pathlib import Path

from nachi.core.config import load_topology, secrets_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("topology")
    parser.add_argument("--secrets-dir", default=None)
    parser.add_argument("--force", action="store_true", help="replace existing keys")
    args = parser.parse_args(argv)

    topology = load_topology(args.topology)
    path: Path = secrets_path(topology, args.secrets_dir)
    existing: dict[str, str] = {}
    if path.exists() and not args.force:
        existing = {
            str(k): str(v)
            for k, v in tomllib.loads(path.read_text("utf-8")).get("keys", {}).items()
        }

    keys = {name: existing.get(name) or secrets.token_urlsafe(32) for name in topology.services}
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# API keys for topology {topology.name!r}. Generated by scripts/gen_keys.py.",
        "# Never commit this file.",
        "[keys]",
        *(f'{name} = "{value}"' for name, value in keys.items()),
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    added = sorted(set(keys) - set(existing))
    print(f"wrote {path} ({len(keys)} keys, new: {', '.join(added) or 'none'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
